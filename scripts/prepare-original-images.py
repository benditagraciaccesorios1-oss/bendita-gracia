"""Optimize supplied product photographs without modifying the uploads.

The first upload is a flyer and the last a palette, not catalog products.
Group framing retains both complete rose candles. Small detail crops are optional
secondary gallery views and are never upscaled by the presentation component.
"""
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'public/images/originals'
OUT.mkdir(parents=True, exist_ok=True)
SOURCES = {
    'figuras-navidenas': ('3.56.56 PM', None),
    'copos-en-caja': ('3.56.57 PM (1)', None),
    'sachet-navideno': ('3.56.57 PM (2)', None),
    'sachet-en-caja': ('3.56.57 PM', None),
    # Remove only the empty upper background; retain both complete candles and their base.
    'rosas-conjunto': ('4.02.18 PM (1)', (0, 280, 736, 860)),
    'rosas-rosa': ('4.02.18 PM (1)', (330, 400, 650, 710)),
    'rosas-marfil': ('4.02.18 PM (1)', (70, 350, 365, 665)),
    'peonia-en-domo': ('4.02.18 PM (2)', None),
    'figuras-con-estrella': ('4.02.18 PM', None),
    'sachet-botanico-rosa': ('4.02.19 PM (1)', None),
    'sachet-flor-azul': ('4.02.19 PM (2)', None),
    'sachet-flor-rosa': ('4.02.19 PM (3)', None),
    'sachet-botanico': ('4.02.19 PM (4)', None),
    'sachet-flores-conjunto': ('4.02.19 PM (5)', None),
    'sachet-flor-empaque': ('4.02.19 PM', None),
}
sizes = {}
for name, (stamp, crop) in SOURCES.items():
    source = ROOT / 'images' / f'WhatsApp Image 2026-11-02 at {stamp}.jpeg'
    with Image.open(source) as original:
        image = ImageOps.exif_transpose(original).convert('RGB')
        if crop:
            image = image.crop(crop)
        # Keep the source resolution. Display code must not enlarge the photograph.
        sizes[f'/images/originals/{name}.webp'] = list(image.size)
        image.save(OUT / f'{name}.webp', quality=96, method=6)
    print(f'{name}.webp')

metadata = ROOT / 'src/data/image-sizes.ts'
metadata.write_text(
    '// Generated by scripts/prepare-original-images.py. Dimensions of the supplied photographs.\n'
    + 'export const originalImageSizes: Record<string, [number, number]> = '
    + json.dumps(sizes, indent=2) + ';\n', encoding='utf-8',
)
